const crypto = require("crypto");

const BASE_URL = "https://api.razorpay.com/v1";

// No RAZORPAY_KEY_ID => mock mode (nothing is sent to Razorpay, same idea as
// the earlier gateway util: the app still works end-to-end for local dev).
function isMockMode() {
  return !process.env.RAZORPAY_KEY_ID;
}

// Safety net: the project is meant to run in TEST mode only for now. If someone
// pastes a live key (rzp_live_...) while RAZORPAY_ENV is not explicitly "live",
// refuse to talk to Razorpay instead of silently charging real money.
function assertKeysMatchEnvironment() {
  const keyId = process.env.RAZORPAY_KEY_ID || "";
  const env = process.env.RAZORPAY_ENV === "live" ? "live" : "test";
  if (env === "test" && !keyId.startsWith("rzp_test_")) {
    throw new Error(
      "RAZORPAY_ENV is 'test' but RAZORPAY_KEY_ID is not a test key (rzp_test_...). Refusing to continue."
    );
  }
}

function safeEqualHex(expected, received) {
  if (typeof received !== "string") return false;
  const a = Buffer.from(expected, "utf8");
  const b = Buffer.from(received, "utf8");
  if (a.length !== b.length) return false;
  return crypto.timingSafeEqual(a, b);
}

// Razorpay order ids are generated by Razorpay (order_XXXX). Our own reference
// goes in `receipt`. Amount is given in rupees and converted to paise here.
async function createOrder({ receipt, amount, customerId, customerPhone, customerEmail }) {
  const paise = Math.round(Number(amount) * 100);
  if (!Number.isFinite(paise) || paise < 100) {
    throw new Error("Amount must be at least ₹1");
  }

  if (isMockMode()) {
    console.log(`[MOCK RAZORPAY] Created order for receipt ${receipt} (₹${amount})`);
    return {
      mocked: true,
      order_id: `order_mock_${receipt}`,
      amount: paise,
      currency: "INR",
      key_id: null,
    };
  }

  assertKeysMatchEnvironment();

  const auth = Buffer.from(
    `${process.env.RAZORPAY_KEY_ID}:${process.env.RAZORPAY_KEY_SECRET}`
  ).toString("base64");

  const response = await fetch(`${BASE_URL}/orders`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Basic ${auth}`,
    },
    body: JSON.stringify({
      amount: paise,
      currency: "INR",
      receipt,
      notes: {
        customer_id: String(customerId),
        customer_phone: customerPhone || "",
        customer_email: customerEmail || "",
      },
    }),
  });

  const data = await response.json();
  if (!response.ok) {
    throw new Error(data?.error?.description || "Razorpay order creation failed");
  }

  return {
    order_id: data.id,
    amount: data.amount,
    currency: data.currency,
    key_id: process.env.RAZORPAY_KEY_ID,
  };
}

// Verifies the three values Razorpay Checkout hands to the browser after a
// successful payment: HMAC-SHA256(order_id + "|" + payment_id, key_secret), hex.
function verifyPaymentSignature({ orderId, paymentId, signature }) {
  if (isMockMode()) return true;
  if (!orderId || !paymentId || !signature) return false;

  const expected = crypto
    .createHmac("sha256", process.env.RAZORPAY_KEY_SECRET || "")
    .update(`${orderId}|${paymentId}`)
    .digest("hex");
  return safeEqualHex(expected, signature);
}

// Webhook signature: HMAC-SHA256 of the RAW request body using the webhook
// secret (set separately in the Razorpay dashboard — it is NOT the key secret),
// sent in the X-Razorpay-Signature header, hex encoded.
function verifyWebhookSignature({ rawBody, signature }) {
  // Full mock mode (no keys at all): accept, so local testing needs no secrets.
  if (isMockMode() && !process.env.RAZORPAY_WEBHOOK_SECRET) return true;

  // Real keys configured but no webhook secret => never accept unsigned calls.
  if (!process.env.RAZORPAY_WEBHOOK_SECRET) return false;
  if (!rawBody || !signature) return false;

  const expected = crypto
    .createHmac("sha256", process.env.RAZORPAY_WEBHOOK_SECRET)
    .update(rawBody)
    .digest("hex");
  return safeEqualHex(expected, signature);
}

module.exports = { createOrder, verifyPaymentSignature, verifyWebhookSignature };
